#!/usr/bin/env python3
"""Generate the HIL vector set and the C header embedded in the PS application.

Vectors and expected outputs come from the same bit-exact Python model used by
the RTL testbenches (model/gen_vectors_lut.py), so the PS run and the
xsim run check the hardware against one source of truth.

usage: gen_hil_vectors.py [nvec] [N]
Outputs:
  vectors/pevec_n16_k{0,4}.hex        (same format as the RTL testbench)
  sw/hil_vectors.h                    (C arrays + FNV-1a reference hashes)
  vectors/manifest.json
"""
import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL = os.path.join(ROOT, "model", "gen_vectors_lut.py")
NVEC = int(sys.argv[1]) if len(sys.argv) > 1 else 2000
N = int(sys.argv[2]) if len(sys.argv) > 2 else 16
KS = [0, 4]
FNV_OFF = 0x811C9DC5
FNV_PRIME = 16777619
MASK = 0xFFFFFFFF


def fnv_words(words):
    h = FNV_OFF
    for w in words:
        for _ in range(4):
            h ^= (w & 0xFF)
            h = (h * FNV_PRIME) & MASK
            w >>= 8
    return h


def load_hex(path, nvec, n):
    rows = []
    with open(path) as f:
        for line in f:
            parts = line.split()
            if not parts:
                continue
            vals = [int(p, 16) for p in parts]
            if len(vals) != 2 * n + 2:
                raise SystemExit(f"{path}: expected {2*n+2} words, got {len(vals)}")
            rows.append(vals)
    if len(rows) != nvec:
        raise SystemExit(f"{path}: expected {nvec} rows, got {len(rows)}")
    return rows


def main():
    os.makedirs(os.path.join(ROOT, "vectors"), exist_ok=True)
    os.makedirs(os.path.join(ROOT, "sw"), exist_ok=True)
    data = {}
    for k in KS:
        out = os.path.join(ROOT, "vectors", f"pevec_n{N}_k{k}.hex")
        subprocess.run(
            [sys.executable, "-I", MODEL, "pe", str(N), str(k), str(NVEC), out, "0.5"],
            check=True)
        rows = load_hex(out, NVEC, N)
        y_exp = [r[-1] for r in rows]
        data[k] = {
            "path": out,
            "rows": rows,
            "fnv_exp": fnv_words(y_exp),
            "sha256": hashlib.sha256(open(out, "rb").read()).hexdigest(),
        }

    hpath = os.path.join(ROOT, "sw", "hil_vectors.h")
    with open(hpath, "w") as f:
        f.write("// AUTO-GENERATED by vectors/gen_hil_vectors.py -- do not edit.\n")
        f.write("// Each row: X[0..N-1], W[0..N-1], BIAS, EXPECTED_Y.\n")
        f.write("#ifndef HIL_VECTORS_H\n#define HIL_VECTORS_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define HIL_N {N}\n#define HIL_NVEC {NVEC}\n\n")
        for k in KS:
            f.write(f"#define HIL_FNV_EXPECTED_K{k} 0x{data[k]['fnv_exp']:08X}u\n")
            f.write(f"static const uint32_t hil_vec_k{k}[HIL_NVEC][{2*N+2}] = {{\n")
            for r in data[k]["rows"]:
                f.write("  {" + ", ".join(f"0x{v:08X}u" for v in r) + "},\n")
            f.write("};\n\n")
        f.write("#endif\n")

    manifest = {
        "nvec": NVEC, "N": N, "sparsity": 0.5,
        "fnv_expected": {str(k): f"0x{data[k]['fnv_exp']:08X}" for k in KS},
        "sha256": {str(k): data[k]["sha256"] for k in KS},
        "source": os.path.relpath(MODEL, ROOT),
    }
    with open(os.path.join(ROOT, "vectors", "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
